-- QA-09 (pendiente #101): la clave privada de recuperación organizacional
-- (F-16) deja de custodiarla el servidor. El par lo genera el navegador de un
-- admin de organización, que sella la privada para cada admin
-- (`org_recovery_key_envelopes`); el servidor guarda sólo bytes opacos y
-- aplica el umbral. El re-sellado para el solicitante lo hace el navegador de
-- un custodio (`awaiting_custodian` -> `approved`).
--
-- Rotación (decisión del usuario): la clave vieja, custodiada por el
-- servidor con `ELLKAN_SECRETS_KEY`, sigue sirviendo para los escrows que
-- todavía la usan; cada usuario re-sella el suyo con la clave nueva en su
-- próximo login. Cuando no queda ninguno (o cuando un admin lo decide) se
-- purga: se borra la privada y los escrows que seguían en ella.

-- 1) Varias claves: la vigente es la de mayor `id`.
alter table org_recovery_keys drop constraint org_recovery_keys_id_check;
alter table org_recovery_keys alter column id drop default;
alter table org_recovery_keys alter column id add generated by default as identity (start with 2);
alter table org_recovery_keys alter column encrypted_private_key drop not null;
alter table org_recovery_keys alter column private_key_nonce drop not null;
alter table org_recovery_keys
    add column custody text not null default 'server' check (custody in ('server', 'client')),
    add column created_by uuid references users(id) on delete set null,
    add column purged_at timestamptz;
-- Una clave de cliente nunca tiene privada en el servidor; una del servidor
-- la tiene hasta que se purga.
alter table org_recovery_keys add constraint org_recovery_keys_custodia_check check (
    (custody = 'client' and encrypted_private_key is null and private_key_nonce is null and purged_at is null)
    or (custody = 'server' and (purged_at is null) = (encrypted_private_key is not null))
);

-- 2) La privada de cada clave de cliente, sellada para cada custodio (su
-- X25519 de `user_keys`). Sólo la abre su navegador.
create table org_recovery_key_envelopes (
    org_recovery_key_id integer not null references org_recovery_keys(id) on delete cascade,
    admin_id uuid not null references users(id) on delete cascade,
    sealed_private_key bytea not null check (octet_length(sealed_private_key) between 1 and 512),
    sealed_by uuid references users(id) on delete set null,
    created_at timestamptz not null default now(),
    primary key (org_recovery_key_id, admin_id)
);

-- 3) Umbral alcanzado sobre una clave de cliente: falta que un custodio
-- re-selle. Cuenta como abierta para "una sola pendiente por escrow".
alter table account_recovery_requests drop constraint account_recovery_requests_status_check;
alter table account_recovery_requests add constraint account_recovery_requests_status_check
    check (status in ('unconfirmed', 'pending', 'awaiting_custodian', 'approved', 'rejected', 'completed', 'expired'));
drop index account_recovery_requests_pendiente_unica_idx;
create unique index account_recovery_requests_pendiente_unica_idx
    on account_recovery_requests(escrow_id) where status in ('pending', 'awaiting_custodian');

