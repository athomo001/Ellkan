-- spec/15 §2 (pendiente #53): sincronización automática con el directorio y
-- freno de bajas masivas.
--   - `auto_sync_enabled` + `poll_interval_seconds`: el servidor corre el
--     «aplicar» solo, cada N segundos (default 60). Apagado por defecto: una
--     instalación ya configurada no empieza a desactivar gente sin que un
--     admin lo prenda.
--   - `max_deactivations_per_run`: más bajas que esto en una corrida la
--     abortan entera (§2.5). Null = automático: 10 % de las cuentas
--     gestionadas activas, mínimo 5. También se aborta si el directorio
--     devuelve 0 usuarios y antes había alguno.

alter table directory_sync_config
    add column auto_sync_enabled boolean not null default false,
    add column poll_interval_seconds integer not null default 60 check (poll_interval_seconds between 30 and 86400),
    add column max_deactivations_per_run integer check (max_deactivations_per_run >= 1),
    add column last_auto_sync_error text;

